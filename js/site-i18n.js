(function () {
  const STORAGE_KEY = 'site-lang';
  const page = document.body.dataset.page;
  const html = document.documentElement;
  const metaDesc = document.querySelector('meta[name="description"]');

  function getDefaultLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'zh' || saved === 'en') return saved;
    } catch (e) {}
    return 'en';
  }

  function applyLang(lang) {
    const dict = SITE_I18N[lang];
    if (!dict) return;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const text = dict[key];
      if (text === undefined) return;
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) {
        el.setAttribute(attr, text);
      } else if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = text;
      } else {
        el.textContent = text;
      }
    });

    const title = dict['meta.' + page + '.title'];
    if (title) document.title = title;
    const desc = dict['meta.' + page + '.description'];
    if (desc && metaDesc) metaDesc.content = desc;

    html.lang = lang === 'zh' ? 'zh-Hant' : 'en';

    const toggle = document.getElementById('lang-toggle');
    if (toggle) {
      toggle.textContent = lang === 'zh' ? 'EN' : '中文';
      toggle.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切換為中文');
      toggle.setAttribute('data-lang', lang === 'zh' ? 'en' : 'zh');
    }

    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
  }

  const initial = getDefaultLang();
  if (initial !== 'en') applyLang(initial);

  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.setAttribute('data-lang', initial === 'zh' ? 'en' : 'zh');
    toggle.addEventListener('click', () => {
      applyLang(toggle.getAttribute('data-lang') || 'zh');
    });
  }
})();
